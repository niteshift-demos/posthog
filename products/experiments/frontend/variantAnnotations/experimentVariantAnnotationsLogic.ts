export const experimentVariantAnnotationsLogic = kea<experimentVariantAnnotationsLogicType>([
    path((key) => [
        'products',
        'experiments',
        'frontend',
        'variantAnnotations',
        'experimentVariantAnnotationsLogic',
        key,
    ]),
    props({} as ExperimentVariantAnnotationsLogicProps),
    key((props) => props.experimentId),

    connect(() => ({
        values: [userLogic, ['user']],
    })),

    actions({
        setDraftVariantKey: (variantKey: string | null) => ({ variantKey }),
        setDraftContent: (content: string) => ({ content }),
        resetDraft: true,
        startEditing: (annotation: ExperimentVariantAnnotationApi) => ({ annotation }),
        setEditingAnnotation: (editing: Partial<EditingAnnotation>) => ({ editing }),
        cancelEditing: true,
        loadMoreAnnotations: true,
        setNextUrl: (nextUrl: string | null) => ({ nextUrl }),
    }),

    reducers({
        draftVariantKey: [
            null as string | null,
            {
                setDraftVariantKey: (_, { variantKey }) => variantKey,
            },
        ],
        draftContent: [
            '',
            {
                setDraftContent: (_, { content }) => content,
                resetDraft: () => '',
            },
        ],
        // Serialize reads and writes so an arriving page cannot restore a deleted or edited note.
        pendingAction: [
            null as PendingAnnotationAction | null,
            {
                createAnnotation: () => 'create',
                updateAnnotation: () => 'update',
                deleteAnnotation: () => 'delete',
                loadAnnotations: () => 'load',
                loadNextPage: () => 'load',
                loadAnnotationsSuccess: () => null,
                loadAnnotationsFailure: () => null,
                loadNextPageSuccess: () => null,
                loadNextPageFailure: () => null,
                createAnnotationSuccess: () => null,
                createAnnotationFailure: () => null,
                updateAnnotationSuccess: () => null,
                updateAnnotationFailure: () => null,
                deleteAnnotationSuccess: () => null,
                deleteAnnotationFailure: () => null,
            },
        ],
        editingAnnotation: [
            null as EditingAnnotation | null,
            {
                startEditing: (_, { annotation }) => ({
                    id: annotation.id,
                    variantKey: annotation.variant_key,
                    content: annotation.content,
                }),
                setEditingAnnotation: (state, { editing }) => (state ? { ...state, ...editing } : state),
                cancelEditing: () => null,
            },
        ],
        nextUrl: [null as string | null, { setNextUrl: (_, { nextUrl }) => nextUrl }],
        loadMoreError: [
            false,
            {
                loadNextPage: () => false,
                loadNextPageSuccess: () => false,
                loadNextPageFailure: () => true,
            },
        ],
    }),

    loaders(({ props, values, actions }) => ({
        // null until the first load resolves, so the panel can tell "loading" apart from "no notes yet"
        annotations: [
            null as ExperimentVariantAnnotationApi[] | null,
            {
                loadAnnotations: async () => {
                    const response = await experimentsVariantAnnotationsList(projectId(), props.experimentId, {
                        limit: 20,
                    })
                    actions.setNextUrl(response.next ?? null)
                    return response.results
                },
                loadNextPage: async () => {
                    const cursor = new URL(values.nextUrl!, window.location.origin).searchParams.get('cursor')!
                    const response = await experimentsVariantAnnotationsList(projectId(), props.experimentId, {
                        limit: 20,
                        cursor,
                    })
                    actions.setNextUrl(response.next ?? null)
                    const loaded = values.annotations ?? []
                    const loadedIds = new Set(loaded.map(({ id }) => id))
                    return [...loaded, ...response.results.filter(({ id }) => !loadedIds.has(id))]
                },
                createAnnotation: async ({ variantKey, content }: { variantKey: string; content: string }) => {
                    const created = await experimentsVariantAnnotationsCreate(projectId(), props.experimentId, {
                        variant_key: variantKey,
                        content: content.trim(),
                    })
                    // If the first load failed there is no list to prepend to, so fetch the real one
                    if (values.annotations === null) {
                        const response = await experimentsVariantAnnotationsList(projectId(), props.experimentId, {
                            limit: 20,
                        })
                        actions.setNextUrl(response.next ?? null)
                        return response.results
                    }
                    return [created, ...values.annotations]
                },
                updateAnnotation: async ({ id, variantKey, content }: EditingAnnotation) => {
                    const original = values.annotations?.find((annotation) => annotation.id === id)
                    // Only send the variant when it changed, so notes on a variant since removed from the flag stay editable
                    const updated = await experimentsVariantAnnotationsPartialUpdate(
                        projectId(),
                        props.experimentId,
                        id,
                        {
                            content: content.trim(),
                            ...(original?.variant_key !== variantKey ? { variant_key: variantKey } : {}),
                        }
                    )
                    return (values.annotations ?? []).map((annotation) =>
                        annotation.id === updated.id ? updated : annotation
                    )
                },
                deleteAnnotation: async (id: string) => {
                    await experimentsVariantAnnotationsDestroy(projectId(), props.experimentId, id)
                    return (values.annotations ?? []).filter((annotation) => annotation.id !== id)
                },
            },
        ],
    })),

    selectors({
        canSubmitDraft: [
            (s) => [s.draftVariantKey, s.draftContent],
            (draftVariantKey: string | null, draftContent: string): boolean =>
                !!draftVariantKey && draftContent.trim().length > 0,
        ],
        currentUserId: [(s) => [s.user], (user: UserType | null): number | null => user?.id ?? null],
    }),

    listeners(({ actions, values }) => ({
        loadMoreAnnotations: () => {
            if (values.nextUrl && !values.annotationsLoading && !values.pendingAction) {
                actions.loadNextPage()
            }
        },
        createAnnotationSuccess: () => {
            actions.resetDraft()
            lemonToast.success('Annotation added')
        },
        updateAnnotationSuccess: () => {
            actions.cancelEditing()
        },
        deleteAnnotationSuccess: () => {
            lemonToast.success('Annotation deleted')
        },
    })),

    afterMount(({ actions }) => {
        actions.loadAnnotations()
    }),
])
