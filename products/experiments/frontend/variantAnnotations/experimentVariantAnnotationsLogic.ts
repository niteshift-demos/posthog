// Mirrors the API serializer's max_length on content.
export const MAX_ANNOTATION_LENGTH = 5000

export type PendingAnnotationAction = 'create' | 'update' | 'delete'

const projectId = (): string => String(ApiConfig.getCurrentProjectId())

const fetchAnnotations = async (experimentId: number): Promise<ExperimentVariantAnnotationApi[]> => {
    const response = await experimentsVariantAnnotationsList(projectId(), experimentId, { limit: 500 })
    return response.results
}

