export type annotationsLogicType = MakeLogicType<
    annotationsLogicValues,
    annotationsLogicActions,
    Record<string, any>,
    annotationsLogicMeta
>

export const annotationsLogic = kea<annotationsLogicType>([
    path(['products', 'annotations', 'frontend', 'annotationsLogic']),
    connect(() => ({ values: [teamLogic, ['currentTeamId']] })),
    actions({
        setFilters: (filters: Partial<AnnotationFilters>) => ({ filters }),
        restoreFilters: (filters: AnnotationFilters, page: number, view: AnnotationView) => ({ filters, page, view }),
        clearFilters: true,
        setDates: (dateFrom: string | null, dateTo: string | null) => ({ dateFrom, dateTo }),
        setView: (view: AnnotationView) => ({ view }),
        setPage: (page: number) => ({ page }),
    }),
    loaders(({ values }) => ({
        explorerData: [
            null as ExplorerData | null,
            {
                loadExplorer: async (_: void, breakpoint) => {
                    await breakpoint(250)
                    const projectId = String(values.currentTeamId)
                    const filters = values.apiFilters
                    const [page, summary] = await Promise.all([
                        api.annotationsList(projectId, {
                            ...filters,
                            limit: ANNOTATIONS_PAGE_SIZE,
                            offset: (values.page - 1) * ANNOTATIONS_PAGE_SIZE,
                        }),
                        api.annotationsSummaryRetrieve(projectId, filters),
                    ])
                    breakpoint()
                    return { page, summary }
                },
            },
        ],
        dashboardOptions: [
            [] as ResourceOption[],
            {
                loadDashboardOptions: async (search: string = '', breakpoint) => {
                    await breakpoint(250)
                    const result = await dashboardApi.dashboardsList(String(values.currentTeamId), {
                        search,
                        limit: 20,
                    })
                    breakpoint()
                    return result.results.map((dashboard) => ({
                        key: String(dashboard.id),
                        label: dashboard.name || `Dashboard ${dashboard.id}`,
                    }))
                },
            },
        ],
        insightOptions: [
            [] as ResourceOption[],
            {
                loadInsightOptions: async (search: string = '', breakpoint) => {
                    await breakpoint(250)
                    const result = await insightApi.insightsList(String(values.currentTeamId), {
                        search,
                        limit: 20,
                        basic: true,
                        saved: true,
                    })
                    breakpoint()
                    return result.results.map((insight) => ({
                        key: String(insight.id),
                        label: insight.name || insight.derived_name || `Insight ${insight.id}`,
                    }))
                },
            },
        ],
    })),
    reducers({
        filters: [
            defaultFilters,
            {
                setFilters: (state, { filters }) => ({ ...state, ...filters }),
                restoreFilters: (_, { filters }) => filters,
                clearFilters: () => defaultFilters,
            },
        ],
        view: [
            'table' as AnnotationView,
            {
                setView: (_, { view }) => view,
                restoreFilters: (_, { view }) => view,
            },
        ],
        page: [
            1,
            {
                setPage: (_, { page }) => page,
                restoreFilters: (_, { page }) => page,
                setFilters: () => 1,
                clearFilters: () => 1,
            },
        ],
        explorerError: [
            null as string | null,
            {
                loadExplorer: () => null,
                loadExplorerSuccess: () => null,
                loadExplorerFailure: (_, { error }) => error,
            },
        ],
    }),
    selectors({
        apiFilters: [
            (s) => [s.filters],
            (filters: AnnotationFilters): AnnotationsListParams => ({
                search: filters.search || undefined,
                date_from: filters.dateFrom ? resolveAnnotationDate(filters.dateFrom, false) : undefined,
                date_to: filters.dateTo
                    ? resolveAnnotationDate(filters.dateTo, true)
                    : filters.dateFrom?.startsWith('-')
                      ? dayjs.utc().toISOString()
                      : undefined,
                scope: filters.scope || undefined,
                dashboard_id: filters.dashboardId || undefined,
                dashboard_item: filters.insightId || undefined,
                hidden_in_user_interface: false,
            }),
        ],
        hasFilters: [(s) => [s.filters], (filters: AnnotationFilters): boolean => Object.values(filters).some(Boolean)],
        timelineDays: [
            (s) => [s.explorerData],
            (data: ExplorerData | null): AnnotationDay[] => {
                const days = new Map<string, AnnotationApi[]>()
                for (const annotation of data?.page.results || []) {
                    const date = annotation.date_marker
                        ? dayjs.utc(annotation.date_marker).format('YYYY-MM-DD')
                        : 'Undated'
                    days.set(date, [...(days.get(date) || []), annotation])
                }
                return [...days].map(([date, annotations]) => ({
                    date,
                    annotations,
                    count:
                        date === 'Undated' && data
                            ? data.summary.total -
                              data.summary.daily_counts.reduce((total, day) => total + day.count, 0)
                            : (data?.summary.daily_counts.find((day) => day.date === date)?.count ??
                              annotations.length),
                }))
            },
        ],
    }),
    listeners(({ actions, values }) => ({
        loadExplorerSuccess: ({ explorerData }) => {
            const lastPage = Math.max(1, Math.ceil(explorerData.page.count / ANNOTATIONS_PAGE_SIZE))
            if (values.page > lastPage) {
                actions.setPage(lastPage)
            }
        },
        setFilters: () => actions.loadExplorer(),
        restoreFilters: () => actions.loadExplorer(),
        clearFilters: () => actions.loadExplorer(),
        setPage: () => actions.loadExplorer(),
        setDates: ({ dateFrom, dateTo }) =>
            actions.setFilters({ dateFrom: dateFrom === 'all' ? null : dateFrom, dateTo }),
        [annotationsModel.actionTypes.appendAnnotations]: () => actions.loadExplorer(),
        [annotationsModel.actionTypes.replaceAnnotation]: () => actions.loadExplorer(),
        [annotationsModel.actionTypes.deleteAnnotationSuccess]: () => actions.loadExplorer(),
    })),
    actionToUrl(({ values }) => {
        const toUrl = (): [string, Record<string, string | number | undefined>, Record<string, unknown>] => [
            urls.annotations(),
            {
                ...router.values.searchParams,
                search: values.filters.search || undefined,
                date_from: values.filters.dateFrom || undefined,
                date_to: values.filters.dateTo || undefined,
                scope: values.filters.scope || undefined,
                dashboard_id: values.filters.dashboardId || undefined,
                dashboard_item: values.filters.insightId || undefined,
                view: values.view === 'table' ? undefined : values.view,
                page: values.page === 1 ? undefined : values.page,
            },
            router.values.hashParams,
        ]
        return { setFilters: toUrl, clearFilters: toUrl, setView: toUrl, setPage: toUrl }
    }),
    urlToAction(({ actions, values }) => ({
        [urls.annotations()]: (_, params) => {
            const scope = params.scope === 'insight' ? 'dashboard_item' : params.scope
            const filters: AnnotationFilters = {
                search: typeof params.search === 'string' ? params.search : '',
                dateFrom: typeof params.date_from === 'string' && params.date_from !== 'all' ? params.date_from : null,
                dateTo: typeof params.date_to === 'string' ? params.date_to : null,
                scope: ['project', 'organization', 'dashboard', 'dashboard_item', 'recording'].includes(scope)
                    ? scope
                    : null,
                dashboardId:
                    Number.isSafeInteger(Number(params.dashboard_id)) && Number(params.dashboard_id) > 0
                        ? Number(params.dashboard_id)
                        : null,
                insightId:
                    Number.isSafeInteger(Number(params.dashboard_item)) && Number(params.dashboard_item) > 0
                        ? Number(params.dashboard_item)
                        : null,
            }
            const page = Number.isSafeInteger(Number(params.page)) && Number(params.page) > 0 ? Number(params.page) : 1
            const view = params.view === 'timeline' ? 'timeline' : 'table'
            if (
                JSON.stringify(filters) !== JSON.stringify(values.filters) ||
                page !== values.page ||
                view !== values.view
            ) {
                actions.restoreFilters(filters, page, view)
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadExplorer()
        actions.loadDashboardOptions()
        actions.loadInsightOptions()
    }),
])
