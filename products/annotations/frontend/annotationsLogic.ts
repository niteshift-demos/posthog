import { resolveAnnotationDate } from './utils'

export const ANNOTATIONS_PAGE_SIZE = 20

export interface AnnotationFilters {
    search: string
    dateFrom: string | null
    dateTo: string | null
    scope: AnnotationScopeEnumApi | null
    dashboardId: number | null
    insightId: number | null
}

export type AnnotationView = 'table' | 'timeline'
type ExplorerData = { page: PaginatedAnnotationListApi; summary: AnnotationSummaryApi }
type ResourceOption = { key: string; label: string }
type AnnotationDay = { date: string; annotations: AnnotationApi[]; count: number }

const defaultFilters: AnnotationFilters = {
    search: '',
    dateFrom: null,
    dateTo: null,
    scope: null,
    dashboardId: null,
    insightId: null,
}

